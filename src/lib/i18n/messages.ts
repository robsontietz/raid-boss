const PT_COLOR_TO_KEY = Object.fromEntries(Object.entries(pt.colors).map(([k, v]) => [v, k]));

/** Name of a detected color bucket in the chosen language. */
export function colorName(bucket: string | null | undefined, lang: Lang, fallback?: string | null) {
  if (bucket && MESSAGES[lang].colors[bucket]) return MESSAGES[lang].colors[bucket];
  return fallback ?? null;
}

/**
 * The agent names states in Portuguese when the user gave no custom label
 * ("Cinza", "Outra cor (Laranja)", "Desconhecido"). Translate those; keep custom labels as typed.
 */
export function localizeState(state: string | null | undefined, lang: Lang): string | null {
  if (!state) return null;
  if (lang === "pt") return state;
  const m = MESSAGES[lang];
  if (state === pt.unknownState) return m.unknownState;
  const plainKey = PT_COLOR_TO_KEY[state];
  if (plainKey) return m.colors[plainKey] ?? state;
  const other = /^Outra cor \((.+)\)$/.exec(state);
  if (other) {
    const key = PT_COLOR_TO_KEY[other[1] ?? ""];
    return m.otherColor(key ? (m.colors[key] ?? other[1] ?? "") : (other[1] ?? ""));
  }
  return state;
}
